#---- Basic Powers ----
def power(base, exponent):
    return base ** exponent

def square(x):
    return x * x

def cube(x):
    return x * x * x

def fourth_power(x):
    return x ** 4

def fifth_power(x):
    return x ** 5

def nth_power(base, n):
    return base ** n
